#Como mostrar todos los elementos de un array sin utilizar el indice, es decir con un ciclo exacto. Para eso obvio necesitamos primero un array con datos
Colores=["Rojo","Rosa","Violeta","Amarillo","Verde","Azul",21,0,1.51]
#Ahora necesitamos un ciclo que recorra ese array para mostrar los distintos valores almacenados en cada indice
for I in Colores:
    print(I)

